"""
Generates everything that describes one release: the Homebrew formula,
the Scoop manifest, the winget manifests and the GitHub release notes.

    python release/render.py version
    python release/render.py check-tag v1.0.0
    python release/render.py manifests --sums dist/SHA256SUMS --out . [--version 1.0.0]
    python release/render.py notes --tag v1.0.0 > notes.md

Standard library only, so it also runs on bare containers and runners.
"""

import argparse
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path
from string import Template
from typing import Dict, List, Optional

import versioning

TEMPLATES = Path(__file__).resolve().parent / "templates"
WINGET_DIR = Path("release/winget/manifests/k/kgorczowski/anonimize")
WINGET_FILES = (
    "kgorczowski.anonimize.yaml",
    "kgorczowski.anonimize.installer.yaml",
    "kgorczowski.anonimize.locale.en-US.yaml",
)

# Bot commits that only refresh the manifests are noise in "Changes".
MANIFEST_COMMIT_PREFIX = "release: package manifests"

_TAG = re.compile(r"^v(\d+)\.(\d+)\.(\d+)(-.+)?$")


def _template(name: str) -> Template:
    return Template((TEMPLATES / name).read_text(encoding="utf-8"))


def _write(path: Path, text: str) -> None:
    # LF on every OS: the files are read by brew, Scoop and winget, and
    # committed from a Linux runner.
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def parse_sums(text: str) -> Dict[str, str]:
    """Reads `sha256sum` output into {asset name: lowercase hex digest}."""
    sums = {}
    for line in text.splitlines():
        if not line.strip():
            continue
        digest, name = line.split(None, 1)
        # "*name" marks binary mode in sha256sum output.
        sums[name.strip().lstrip("*")] = digest.lower()
    return sums


def _asset(version: str, sums: Dict[str, str], platform: str):
    name = versioning.archive_name(version, platform)
    if name not in sums:
        raise ValueError(f"SHA256SUMS has no entry for {name}")
    return versioning.download_url(version, name), sums[name]


def render_formula(version: str, sums: Dict[str, str]) -> str:
    arm_url, arm_sha256 = _asset(version, sums, "macos-arm64")
    intel_url, intel_sha256 = _asset(version, sums, "macos-x64")
    return _template("anonimize.rb").substitute(
        repo_url=versioning.REPO_URL,
        version=version,
        arm_url=arm_url,
        arm_sha256=arm_sha256,
        intel_url=intel_url,
        intel_sha256=intel_sha256,
    )


def render_scoop(version: str, sums: Dict[str, str]) -> str:
    url, sha256 = _asset(version, sums, "windows-x64")
    manifest = {
        "##": "Generated by release/render.py for each release; do not edit by hand.",
        "version": version,
        "description": "Anonymize project folders before sharing them",
        "homepage": versioning.REPO_URL,
        "license": "MIT",
        "architecture": {"64bit": {"url": url, "hash": sha256}},
        "bin": "anonimize.exe",
        "suggest": {
            "Tesseract OCR": "main/tesseract",
            "7-Zip": "main/7zip",
        },
        "notes": (
            "Check that the optional OCR and .rar tools were found: "
            "anonimize --check-tools"
        ),
    }
    return json.dumps(manifest, indent=4) + "\n"


def render_winget(version: str, sums: Dict[str, str]) -> Dict[str, str]:
    url, sha256 = _asset(version, sums, "windows-x64")
    values = {
        "version": version,
        "url": url,
        "sha256": sha256.upper(),
        "repo_url": versioning.REPO_URL,
    }
    return {
        name: _template(f"winget/{name}").substitute(values)
        for name in WINGET_FILES
    }


def write_manifests(version: str, sums: Dict[str, str], out: Path) -> None:
    # An incomplete SHA256SUMS means an incomplete release: refuse before
    # writing anything.
    for platform in versioning.PLATFORMS:
        _asset(version, sums, platform)

    _write(out / "Formula" / "anonimize.rb", render_formula(version, sums))
    _write(out / "bucket" / "anonimize.json", render_scoop(version, sums))

    winget_root = out / WINGET_DIR
    if winget_root.is_dir():
        for old in winget_root.iterdir():
            if old.name != version:
                shutil.rmtree(old) if old.is_dir() else old.unlink()
    for name, content in render_winget(version, sums).items():
        _write(winget_root / version / name, content)


def _tag_numbers(tag: str):
    match = _TAG.match(tag)
    return tuple(int(part) for part in match.groups()[:3]) if match else None


def previous_final_tag(tags: List[str], current_tag: str) -> Optional[str]:
    """The newest vX.Y.Z (no pre-release suffix) older than current_tag."""
    current = _tag_numbers(current_tag)
    if current is None:
        raise ValueError(f"not a release tag: {current_tag}")
    finals = [
        tag
        for tag in tags
        if _TAG.match(tag)
        and _TAG.match(tag).group(4) is None
        and _tag_numbers(tag) < current
    ]
    return max(finals, key=_tag_numbers, default=None)


def render_release_notes(version: str, changes: Optional[List[str]]) -> str:
    """changes=None means there is no earlier release to compare with."""
    if changes is None:
        change_text = "First packaged release."
    elif not changes:
        change_text = "No code changes since the previous release."
    else:
        change_text = "\n".join(f"- {subject}" for subject in changes)

    deb_name = versioning.deb_name(version)
    return _template("release-notes.md").substitute(
        repo_url=versioning.REPO_URL,
        deb_name=deb_name,
        deb_url=versioning.download_url(version, deb_name),
        linux_archive=versioning.archive_name(version, "linux-x64"),
        changes=change_text,
    )


def _git(*args: str) -> str:
    return subprocess.run(
        ["git", *args],
        cwd=versioning.ROOT,
        check=True,
        capture_output=True,
        text=True,
        encoding="utf-8",
    ).stdout


def changes_since_previous_release(tag: str) -> Optional[List[str]]:
    previous = previous_final_tag(_git("tag", "--list", "v*").split(), tag)
    if previous is None:
        return None
    subjects = _git(
        "log", "--no-merges", "--format=%s", f"{previous}..{tag}"
    ).splitlines()
    return [
        subject
        for subject in subjects
        if subject and not subject.startswith(MANIFEST_COMMIT_PREFIX)
    ]


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    commands = parser.add_subparsers(dest="command", required=True)

    commands.add_parser("version", help="print __version__ of anonymize.py")

    check = commands.add_parser("check-tag", help="tag must be v + __version__")
    check.add_argument("tag")

    manifests = commands.add_parser("manifests", help="write package manifests")
    manifests.add_argument("--sums", type=Path, required=True)
    manifests.add_argument("--out", type=Path, required=True)
    manifests.add_argument(
        "--version",
        help="defaults to __version__; pass the tag's version when the "
        "checkout is not the tagged commit",
    )

    notes = commands.add_parser("notes", help="print the release notes")
    notes.add_argument("--tag", required=True)

    args = parser.parse_args(argv)

    if args.command == "version":
        print(versioning.read_version())
    elif args.command == "check-tag":
        version = versioning.read_version()
        try:
            versioning.check_tag(args.tag, version)
        except ValueError as exc:
            print(f"ERROR: {exc}", file=sys.stderr)
            return 1
        print(version)
    elif args.command == "manifests":
        version = args.version or versioning.read_version()
        sums = parse_sums(args.sums.read_text(encoding="utf-8"))
        write_manifests(version, sums, args.out)
    elif args.command == "notes":
        text = render_release_notes(
            args.tag[1:], changes_since_previous_release(args.tag)
        )
        # Commit subjects may be non-ASCII; don't depend on the console's
        # encoding.
        sys.stdout.buffer.write(text.encode("utf-8"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
